import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { iranLocations, provinceCities } from "../../../src/lib/iran-locations";

const root = new URL("../../../", import.meta.url);
const manifest = JSON.parse(readFileSync(new URL("docs/LOCATIONS_SOURCE.json", root), "utf8"));
const sha256 = (relativePath: string) => createHash("sha256")
  .update(readFileSync(fileURLToPath(new URL(relativePath, root)))).digest("hex");

describe("Iran address suggestions preserve reviewed source identity and province boundaries", () => {
  it("ties the snapshot and retained license bytes to the reviewed upstream commit", () => {
    expect(manifest.repository).toBe("https://github.com/tafakoritech/Provinces-and-Cities-of-Iran-Dataset");
    expect(manifest.commit).toBe("e00e125d10259f6f3a5e4802cd336cef89258222");
    expect(manifest.sourceFile).toBe("cities.json");
    // Independently fetched upstream bytes, not regenerated by the importer under test.
    expect(manifest.sourceSha256).toBe("9e5794795917a650e549d724f4656aa0d17146b7d4217e74289ecd6bcf715609");
    expect(manifest.provinceSourceFile).toBe("provinces.json");
    expect(manifest.provinceSourceSha256).toBe("ec960eb63c828cd34d75b0f57b4665781a7407ee808e7382d752bf9852c88713");
    expect(manifest.licenseSha256).toBe("1a3576c17e6c769bf5bde9d996c0194abf6b9b6c7f9ef9f254ccd015dcfdee52");
    expect(manifest.outputSha256).toBe("8cd5bbeaa8e824e072a990a2321ca7039994cb80964a462b8ed842e58fa2b2ff");
    expect(sha256("src/lib/iran-locations.LICENSE.txt")).toBe(manifest.licenseSha256);
    expect(sha256("src/lib/iran-locations.json")).toBe(manifest.outputSha256);
    expect(manifest.license).toBe("MIT");
  });

  it("retains unique source IDs while keeping duplicate city names as separate locations", () => {
    expect(iranLocations).toHaveLength(31);
    expect(manifest.provinceCount).toBe(31);
    expect(new Set(iranLocations.map(province => province.id)).size).toBe(31);
    const cities = iranLocations.flatMap(province => province.cities);
    expect(cities).toHaveLength(1119);
    expect(manifest.cityCount).toBe(1119);
    expect(new Set(cities.map(city => city.id)).size).toBe(cities.length);
    for (const province of iranLocations) {
      expect(province.cities.length).toBeGreaterThan(0);
      for (const name of [province.name, ...province.cities.map(city => city.name)]) {
        expect(name).toBe(name.normalize("NFC"));
        expect(name).not.toMatch(/[يك<>]/);
        expect([...name].some(character => character.codePointAt(0)! < 32)).toBe(false);
        expect(name).toBe(name.trim());
      }
    }
    // Upstream has three distinct سردشت records; a name-only join would mix provinces.
    expect(provinceCities("آذربایجان غربی").filter(city => city.name === "سردشت"))
      .toEqual([{ id: 77, name: "سردشت" }]);
    expect(provinceCities("خوزستان").filter(city => city.name === "سردشت"))
      .toEqual([{ id: 503, name: "سردشت" }]);
    expect(provinceCities("هرمزگان").filter(city => city.name === "سردشت"))
      .toEqual([{ id: 1046, name: "سردشت" }]);
    expect(provinceCities("تهران").some(city => [77, 503, 1046].includes(city.id))).toBe(false);
  });

  it.each([
    ["آذربایجان شرقی", "تبریز", 12], ["البرز", "کرج", 229], ["تهران", "تهران", 301],
    ["فارس", "شیراز", 647], ["کرمان", "کرمان", 781], ["گیلان", "رشت", 920],
  ])("includes %s / %s as an explicit city rather than inferring county names", (province, city, id) => {
    expect(provinceCities(province as string)).toContainEqual({ id, name: city });
  });

  it.each([
    ["  كردستان  ", "کردستان"],
    ["ا\u0653ذربايجان شرقي", "آذربایجان شرقی"],
  ])("accepts equivalent user spelling %s without changing the province's cities", (input, canonical) => {
    expect(provinceCities(input)).toEqual(provinceCities(canonical));
    expect(provinceCities(input).length).toBeGreaterThan(0);
  });

  it("does not suggest another province's cities for an unknown or blank province", () => {
    expect(provinceCities("استان آزمایشی QA که در منبع نیست")).toEqual([]);
    expect(provinceCities(" ")).toEqual([]);
  });

  it("returns an independent suggestion array so UI sorting cannot reorder the shared snapshot", () => {
    const expected = provinceCities("فارس");
    const changed = provinceCities("فارس");
    changed.reverse();
    changed.pop();
    expect(provinceCities("فارس")).toEqual(expected);
  });
});
