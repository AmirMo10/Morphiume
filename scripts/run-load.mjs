import { spawnSync, spawn } from "node:child_process";
import { mkdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { config } from "dotenv";
import { randomUUID } from "node:crypto";
import { controlledQaDatabase } from "../tests/helpers/qa-target.mjs";
config({ path: ".env.local", quiet: true });
controlledQaDatabase(process.env);
const modes = new Set(["smoke", "vu", "rps"]);
const mode = process.argv.find(arg => arg.startsWith("--mode="))?.slice(7) ?? "vu";
if (!modes.has(mode)) throw new Error("Use --mode=smoke|vu|rps");
if (!["test", "staging"].includes(process.env.DEPLOYMENT_ENV ?? "") || process.env.PAYMENT_PROVIDER !== "mock" || process.env.SMS_PROVIDER !== "mock") throw new Error("Load runner requires controlled test/staging; live services are refused");
const fixturePath = resolve(process.env.LOAD_FIXTURE ?? ".local/load-fixture.json");
const fixture = JSON.parse(await readFile(fixturePath, "utf8"));
if (!["test", "staging"].includes(fixture.environment) || fixture.users?.length !== 200 || fixture.productIds?.length !== 200) throw new Error("Prepare an isolated 200-account/200-product fixture first");
const executable = process.env.K6_BIN ?? "k6";
const version = spawnSync(executable, ["version"], { encoding: "utf8", windowsHide: true });
if (version.error || version.status || !/^k6(?:\.exe)? v2\.3\.0\b/.test(version.stdout)) throw new Error("Official verified k6 v2.3.0 binary is required; see docs/qa/PERFORMANCE.md");
const revision = spawnSync("git", ["rev-parse", "HEAD"], { encoding: "utf8", windowsHide: true });
await mkdir("test-results/load", { recursive: true });
const summary = resolve(`test-results/load/${mode}-${Date.now()}.json`);
console.log(`Running ${mode} on isolated ${fixture.environment}. Summary: ${summary}`);
const child = spawn(executable, ["run", "tests/load/morphiume.js"], { stdio: "inherit", windowsHide: true, env: { ...process.env, K6_NO_USAGE_REPORT: "true", LOAD_FIXTURE: fixturePath, LOAD_MODE: mode, LOAD_RUN_ID: randomUUID(), LOAD_SUMMARY: summary, LOAD_APP_COMMIT: process.env.LOAD_APP_COMMIT ?? revision.stdout?.trim() ?? "unrecorded" } });
child.on("error", () => { console.error("k6 could not start"); process.exitCode = 1; });
child.on("exit", code => { process.exitCode = code ?? 1; });
